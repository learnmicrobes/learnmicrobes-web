/*
 * Writes src/data/contentIndex.generated.ts: slug, title, and summary for every
 * Learn topic and Visual Atlas card.
 *
 * The app shell (home page, nav, page titles) needs only these fields. Importing
 * the full Learn and atlas data there would put several hundred KB into the first
 * download of every page, so the shell reads this index instead.
 *
 * Runs automatically before `npm start` and `npm run build`. Commit the output.
 */
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const ROOT = path.resolve(__dirname, '..');
const TARGET = path.join(ROOT, 'src', 'data', 'contentIndex.generated.ts');

// Load the TypeScript data modules directly. They contain plain data and type-only
// imports, so transpiling each file on require is enough.
require.extensions['.ts'] = (module, filename) => {
  const source = fs.readFileSync(filename, 'utf8');
  const { outputText } = ts.transpileModule(source, {
    fileName: filename,
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019, esModuleInterop: true }
  });
  module._compile(outputText, filename);
};

const { learnTopics } = require(path.join(ROOT, 'src', 'data', 'learnTopics.ts'));
const { atlasPages } = require(path.join(ROOT, 'src', 'data', 'atlasPages.ts'));

const pick = ({ slug, title, summary }) => ({ slug, title, summary });

const output = [
  '// Generated by scripts/build-content-index.cjs from learnTopics.ts and atlasPages.ts.',
  '// Do not edit by hand; it is rebuilt before every `npm start` and `npm run build`.',
  '',
  'export type ContentIndexEntry = {',
  '  slug: string;',
  '  title: string;',
  '  summary: string;',
  '};',
  '',
  `export const learnIndex: ContentIndexEntry[] = ${JSON.stringify(learnTopics.map(pick), null, 2)};`,
  '',
  `export const visualIndex: ContentIndexEntry[] = ${JSON.stringify(atlasPages.map(pick), null, 2)};`,
  ''
].join('\n');

const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
if (current !== output) {
  fs.writeFileSync(TARGET, output);
}

console.log(`content index: ${learnTopics.length} Learn topics, ${atlasPages.length} atlas cards${current === output ? ' (unchanged)' : ' (written)'}`);
